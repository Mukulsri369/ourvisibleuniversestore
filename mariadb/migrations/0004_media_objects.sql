CREATE TABLE store_media_objects (
 path VARCHAR(300) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL,
 content_type VARCHAR(100) NOT NULL, byte_length INT UNSIGNED NOT NULL, sha256 CHAR(64) NOT NULL,
 deleted_at DATETIME(6),created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(owner_id) REFERENCES auth_user(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
