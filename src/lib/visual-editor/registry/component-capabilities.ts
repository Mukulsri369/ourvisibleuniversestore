export interface ComponentSlotDefinition {
  slotName: string;
  label: string;
  description: string;
  allowedChildTypes?: readonly ComponentType[];
  maxChildren?: number;
}

export interface TrustedComponentCapabilities {
  readonly type: ComponentType;
  readonly displayName: string;
  readonly category: ComponentCategoryGroup;
  readonly status: ComponentImplementationStatus;
  readonly description: string;
  readonly selectable: boolean;
  readonly draggable: boolean;
  readonly resizable: boolean;
  readonly deletable: boolean;
  readonly duplicable: boolean;
  readonly isLeaf: boolean;
  readonly isRootOnly: boolean;
  readonly isGlobalChrome: boolean;
  readonly isGlobalBackgroundLayer: boolean;
  readonly requiresRouterContext: boolean;
  readonly requiresQueryContext: boolean;
  readonly usesClientOnlyEffects: boolean;
  readonly supportedBindingKinds: readonly DataBinding["kind"][];
  readonly editableProps: readonly (keyof SafeComponentProps)[];
  readonly protectedBusinessFields: readonly string[];
  readonly layoutSupport: Readonly<SupportedLayoutProperties>;
  readonly visualSupport: Readonly<SupportedVisualProperties>;
  readonly animationSupport: Readonly<SupportedAnimationProperties>;
  readonly unsupportedStylePaths: readonly string[];
  readonly supportedSlots: readonly ComponentSlotDefinition[];
  readonly miniPreviewSupported: boolean;
  readonly miniPreviewStrategy: MiniPreviewStrategy;
}

