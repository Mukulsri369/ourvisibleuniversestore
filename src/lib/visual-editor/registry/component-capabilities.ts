function freezeCapability(cap: TrustedComponentCapabilities): TrustedComponentCapabilities {
  return Object.freeze({
    ...cap,
    supportedBindingKinds: Object.freeze([...cap.supportedBindingKinds]),
    editableProps: Object.freeze([...cap.editableProps]),
    protectedBusinessFields: PROTECTED_FIELDS,
    layoutSupport: Object.freeze({ ...cap.layoutSupport }),
    visualSupport: Object.freeze({ ...cap.visualSupport }),
    animationSupport: Object.freeze({ ...cap.animationSupport }),
    unsupportedStylePaths: Object.freeze([...cap.unsupportedStylePaths]),
    supportedSlots: Object.freeze(cap.supportedSlots.map((s) => Object.freeze({ ...s }))),
  });
}

